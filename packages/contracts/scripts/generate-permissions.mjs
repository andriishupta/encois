import { execFile } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { promisify } from "node:util";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const run = promisify(execFile);
const source = JSON.parse(await readFile(resolve(root, "permissions.json"), "utf8"));
const entries = source.permissions;
const keys = new Set(entries.map((entry) => entry.key));

if (source.version !== 1 || entries.length === 0 || entries.some((entry) => !keys.has(entry.key) || entry.implies.some((implied) => !keys.has(implied)))) {
  throw new Error("permissions.json is invalid");
}

function constantName(key) {
  return key.split(":").map((part) => part.replace(/[^a-zA-Z0-9]/g, " ").replace(/(^|\s)([a-z])/g, (_, prefix, letter) => `${prefix}${letter.toUpperCase()}`).replace(/\s/g, "")).join("");
}

const ts = `// Generated by scripts/generate-permissions.mjs. Do not edit manually.\n\nexport const Permission = {\n${entries.map((entry) => `  ${constantName(entry.key)}: ${JSON.stringify(entry.key)},`).join("\n")}\n} as const;\n\nexport type Permission = (typeof Permission)[keyof typeof Permission];\n\nexport const allPermissions = Object.values(Permission) as readonly Permission[];\n\nexport const permissionImplications: Readonly<Record<Permission, readonly Permission[]>> = {\n${entries.map((entry) => `  [Permission.${constantName(entry.key)}]: [${entry.implies.map((implied) => `Permission.${constantName(implied)}`).join(", ")}],`).join("\n")}\n};\n\nexport function isPermission(value: unknown): value is Permission {\n  return typeof value === "string" && allPermissions.includes(value as Permission);\n}\n\nexport function permissionIncludes(granted: readonly Permission[], required: Permission): boolean {\n  return granted.includes(required) || granted.some((permission) => permissionImplications[permission].includes(required));\n}\n`;

const goPermissionNames = entries.map((entry) => `Permission${constantName(entry.key)}`);
const longestGoPermissionName = Math.max(...goPermissionNames.map((name) => name.length));
const go = `// Code generated by scripts/generate-permissions.mjs. DO NOT EDIT.\n\npackage contracts\n\n// Permission identifies a server capability shared across API and UI contracts.\ntype Permission string\n\nconst (\n${entries.map((entry, index) => `\t${goPermissionNames[index].padEnd(longestGoPermissionName)} Permission = ${JSON.stringify(entry.key)}`).join("\n")}\n)\n\nvar AllPermissions = []Permission{\n${goPermissionNames.map((name) => `\t${name},`).join("\n")}\n}\n`;

const tsPath = resolve(root, "src/permissions.generated.ts");
await writeFile(tsPath, ts);
await writeFile(resolve(root, "permissions_generated.go"), go);
await run("biome", ["format", "--write", tsPath]);
